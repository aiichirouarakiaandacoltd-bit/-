def flatten_lines(script_data):
    """Flatten all sections into a single list of narration lines."""
    lines = []
    for section in script_data["sections"]:
        lines.extend(section["lines"])
    return lines


def script_to_text(script_data):
    """Convert script data to plain text."""
    parts = [f"タイトル: {script_data['title']}", ""]
    for section in script_data["sections"]:
        parts.append(f"【{section['label']}】")
        for line in section["lines"]:
            parts.append(line)
        parts.append("")
    return "\n".join(parts)
