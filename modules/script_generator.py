def generate_script(theme: str) -> dict:
    if theme in BUILTIN_SCRIPTS:
        script = BUILTIN_SCRIPTS[theme].copy()
    else:
        script = _generate_generic_script(theme)

    for chapter_name, chapter_data in script["chapters"].items():
        text = chapter_data["narration"]
        char_count = len(text)
        duration_sec = (char_count / NARRATION_SPEED) * 60
        min_duration = CHAPTER_DURATIONS[chapter_name]
        chapter_data["duration"] = max(duration_sec, min_duration)
        chapter_data["char_count"] = char_count

    return script


